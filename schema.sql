CREATE TABLE IF NOT EXISTS users(
  email TEXT PRIMARY KEY,
  nick TEXT NOT NULL,
  salt TEXT NOT NULL,
  hash TEXT NOT NULL,
  age TEXT,
  terms_version TEXT,
  terms_at INTEGER,
  created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions(
  token TEXT PRIMARY KEY,
  email TEXT NOT NULL,
  created_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_email ON sessions(email);
CREATE TABLE IF NOT EXISTS saves(
  email TEXT PRIMARY KEY,
  at INTEGER NOT NULL,
  data TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS attempts(k TEXT NOT NULL, at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS attempts_k ON attempts(k,at);

CREATE TABLE IF NOT EXISTS stats(d TEXT NOT NULL,k TEXT NOT NULL,n INTEGER NOT NULL DEFAULT 0,PRIMARY KEY(d,k));
CREATE TABLE IF NOT EXISTS feedback(id INTEGER PRIMARY KEY AUTOINCREMENT,at INTEGER NOT NULL,kind TEXT NOT NULL,msg TEXT NOT NULL,mail TEXT,meta TEXT,done INTEGER NOT NULL DEFAULT 0);
